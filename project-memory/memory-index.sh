#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MEM_DIR="${1:-.}"
[[ -d "$MEM_DIR" ]] || { echo "Error: memory directory does not exist: $MEM_DIR" >&2; exit 1; }
MEM_DIR="$(cd "$MEM_DIR" && pwd)"
INDEX="$MEM_DIR/MEMORY.md"
HALF_LIFE="${MEMORY_HALF_LIFE:-}"
if [[ -z "$HALF_LIFE" && -f "$INDEX" ]]; then
  HALF_LIFE="$(awk '/^Half-life \(tasks\): / {print $3; exit}' "$INDEX")"
fi
HALF_LIFE="${HALF_LIFE:-10}"
BUDGET="${MEMORY_CONTEXT_BUDGET_BYTES:-32768}"
for value in "$HALF_LIFE" "$BUDGET"; do
  if ! [[ "$value" =~ ^[1-9][0-9]*$ ]] || (( ${#value} > 9 )); then
    echo "Error: half-life and context budget must be positive integers (at most 9 digits)" >&2; exit 1
  fi
done
stage="$(mktemp -d "$MEM_DIR/.index.XXXXXX")"
trap 'rm -rf -- "$stage"' EXIT
files=()
while IFS= read -r file; do files+=("$file"); done < <(find "$MEM_DIR" -maxdepth 2 -type f -name '*.md' ! -name MEMORY.md | LC_ALL=C sort)
: > "$stage/rows"
if (( ${#files[@]} )); then
  # C locale counts UTF-8 bytes for the budget; metadata and paths remain UTF-8.
  LC_ALL=C awk -v memory_dir="$MEM_DIR" -v half_life="$HALF_LIFE" \
    -v rows_output="$stage/rows" -v stats_output="$stage/stats" \
    -f "$SCRIPT_DIR/markdown.awk" -f "$SCRIPT_DIR/index.awk" "${files[@]}"
  { read -r current_seq; read -r row_count; read -r default_bytes; } < "$stage/stats"
else current_seq=0; row_count=0; default_bytes=0
fi
{
  echo '# Memory Index'
  echo
  echo "Last rebuilt: $(date +%Y-%m-%d)"
  echo "Half-life (tasks): $HALF_LIFE"
  echo "Current task seq: $current_seq"
  echo "Index rows: $row_count"
  echo "Default load bytes: $default_bytes"
  echo "Context budget (bytes): $BUDGET"
  echo
  echo '> Auto-generated by memory-index.sh — do not edit by hand.'
  echo '> Recency uses task distance only; importance affects preservation and ranking, not recency.'
  echo '> Load rows marked `always` or `recent:auto`; expand all other rows only when relevant.'
  echo '> For decision links, read only the linked section through the next level-two heading.'
  echo
  echo '| Page | Tier | Load | Last Task | Date | Importance | Recency | Score | Summary |'
  echo '|------|------|------|-----------|------|------------|---------|-------|---------|'
  LC_ALL=C sort -t $'\t' -k1,1nr -k2,2 "$stage/rows" | cut -f2-
} > "$stage/MEMORY.md"
mv "$stage/MEMORY.md" "$INDEX"
if (( default_bytes > BUDGET )); then
  echo "Warning: default context budget exceeded ($default_bytes > $BUDGET bytes); shorten summaries or use load: on-demand" >&2
fi
echo "Rebuilt $INDEX (current_seq=$current_seq, half-life=$HALF_LIFE tasks)"
